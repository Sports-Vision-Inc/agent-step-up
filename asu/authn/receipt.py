"""Approval challenge derivation and offline receipt verification (pure).

This module has no web-framework dependency so that a third party (or the
`asu verify-receipt` CLI) can verify an approval receipt holding only the
user's public key (SPEC P5).

Challenge v2 (D-005 item 1; injective, matches the formal model's tuple):

    c = SHA-256( JCS({"tag": "ASU-APPROVAL-v2", "digest": h, "approval_id": id,
                      "nonce": n, "grant_digest": g | null}) )

``h`` and ``g`` are lowercase hex SHA-256 digests; ``g = SHA-256(JCS(grant))``
of the gateway-built grant when the user delegates "similar" actions, else
null. JCS of an object is injective in its members, so no two (h, id, n, g)
tuples share a challenge (CR-2). v1 receipts (byte concatenation) are
rejected: their signature does not cover a v2 challenge.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import re
from typing import Any, Dict, List, Optional, Union
from urllib.parse import urlsplit

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519

CHALLENGE_TAG = "ASU-APPROVAL-v2"
DOMAIN_TAG = CHALLENGE_TAG.encode()  # kept for importers; v1 byte-concatenation is gone
RECEIPT_VERSION = 2

ALG_ES256 = -7
ALG_EDDSA = -8
SUPPORTED_ALGS = (ALG_ES256, ALG_EDDSA)

FLAG_UP = 0x01
FLAG_UV = 0x04
FLAG_BE = 0x08
FLAG_BS = 0x10

_HEX64 = re.compile(r"^[0-9a-f]{64}$")
# approval ids and nonces are generated by the gateway; we only accept a
# conservative printable alphabet so nothing exotic (NUL, whitespace, unicode
# lookalikes) leaks in. Injectivity comes from the JCS object encoding (v2).
_TOKEN = re.compile(r"^[A-Za-z0-9_\-.:]{1,256}$")


# ----------------------------------------------------------------------------
# base64url helpers
# ----------------------------------------------------------------------------
def b64u_encode(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def b64u_decode(data: Union[str, bytes]) -> bytes:
    if isinstance(data, bytes):
        data = data.decode("ascii")
    if not isinstance(data, str):
        raise ValueError("expected base64url string")
    if not re.fullmatch(r"[A-Za-z0-9_\-]*={0,2}", data):
        raise ValueError("invalid base64url")
    data = data.rstrip("=")
    return base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))


# ----------------------------------------------------------------------------
# canonical hashing of grant constraints
# ----------------------------------------------------------------------------
def jcs(obj: Any) -> bytes:
    """RFC 8785 JSON Canonicalization Scheme.

    Uses the gateway's implementation (asu.jcs) when present so that grant
    digests are byte-identical to the ones the Store checks; falls back to the
    ``rfc8785`` package (same RFC) for standalone/offline use."""
    try:
        from asu import jcs as _gw_jcs  # type: ignore

        return _gw_jcs.canonicalize(obj)
    except ImportError:
        import rfc8785

        return rfc8785.dumps(obj)


def grant_digest(grant_request: Dict[str, Any]) -> str:
    """h_grant = SHA-256(JCS(grant_request)) as lowercase hex."""
    if not isinstance(grant_request, dict):
        raise ValueError("grant_request must be a dict")
    return hashlib.sha256(jcs(grant_request)).hexdigest()


# ----------------------------------------------------------------------------
# challenge
# ----------------------------------------------------------------------------
def _digest_bytes(h: str) -> bytes:
    if not isinstance(h, str) or not _HEX64.match(h.lower()):
        raise ValueError("digest must be a 64-char hex SHA-256")
    return bytes.fromhex(h)


def _token_bytes(value: Union[str, bytes], what: str) -> bytes:
    if isinstance(value, bytes):
        value = value.decode("ascii")
    if not isinstance(value, str) or not _TOKEN.match(value):
        raise ValueError(f"{what} has invalid format")
    return value.encode("utf-8")


def challenge_message(
    digest: str,
    approval_id: str,
    nonce: Union[str, bytes],
    h_grant: Optional[str] = None,
) -> bytes:
    """JCS bytes that the challenge hashes (exposed for tests / third parties)."""
    _digest_bytes(digest)
    if h_grant is not None:
        _digest_bytes(h_grant)
    if isinstance(nonce, bytes):
        nonce = nonce.decode("ascii")
    _token_bytes(approval_id, "approval_id")
    _token_bytes(nonce, "nonce")
    return jcs({
        "tag": CHALLENGE_TAG,
        "digest": digest.lower(),
        "approval_id": approval_id,
        "nonce": nonce,
        "grant_digest": h_grant.lower() if h_grant is not None else None,
    })


def compute_challenge(
    digest: str,
    approval_id: str,
    nonce: Union[str, bytes],
    h_grant: Optional[str] = None,
) -> bytes:
    return hashlib.sha256(challenge_message(digest, approval_id, nonce, h_grant)).digest()


def approval_challenge(approval: Dict[str, Any], with_grant: bool = False) -> bytes:
    """WebAuthn challenge bytes (v2) for an approval record (SPEC section 7).

    ``with_grant=True`` sets ``grant_digest = SHA-256(JCS(approval["grant_request"]))``
    so the user's signature also covers the delegated-grant constraints.
    """
    h_grant = None
    if with_grant:
        gr = approval.get("grant_request")
        if not gr:
            raise ValueError("approval has no grant_request")
        h_grant = grant_digest(gr)
    return compute_challenge(approval["digest"], approval["id"], approval["nonce"], h_grant)


# ----------------------------------------------------------------------------
# public keys
# ----------------------------------------------------------------------------
def load_public_key(public_key: bytes):
    """Accept a COSE_Key (what WebAuthn registration yields and what the
    authenticator routes store), DER SubjectPublicKeyInfo, or PEM."""
    if isinstance(public_key, str):
        public_key = public_key.encode()
    if public_key.startswith(b"-----BEGIN"):
        return serialization.load_pem_public_key(public_key), None
    try:
        import cbor2

        cose = cbor2.loads(public_key)
    except Exception:
        cose = None
    if isinstance(cose, dict) and 1 in cose:
        kty, alg = cose.get(1), cose.get(3)
        if kty == 2 and cose.get(-1) == 1:  # EC2 / P-256
            x, y = cose.get(-2), cose.get(-3)
            if not (isinstance(x, bytes) and isinstance(y, bytes) and len(x) == 32 and len(y) == 32):
                raise ValueError("bad EC2 key")
            key = ec.EllipticCurvePublicNumbers(
                int.from_bytes(x, "big"), int.from_bytes(y, "big"), ec.SECP256R1()
            ).public_key()
            return key, alg if alg is not None else ALG_ES256
        if kty == 1 and cose.get(-1) == 6:  # OKP / Ed25519
            x = cose.get(-2)
            if not (isinstance(x, bytes) and len(x) == 32):
                raise ValueError("bad OKP key")
            return ed25519.Ed25519PublicKey.from_public_bytes(x), alg if alg is not None else ALG_EDDSA
        raise ValueError("unsupported COSE key type")
    return serialization.load_der_public_key(public_key), None


def verify_assertion_signature(public_key: bytes, alg: int, signed: bytes, signature: bytes) -> bool:
    try:
        key, key_alg = load_public_key(public_key)
    except Exception:
        return False
    if key_alg is not None and key_alg != alg:
        return False
    try:
        if alg == ALG_ES256:
            if not isinstance(key, ec.EllipticCurvePublicKey) or not isinstance(key.curve, ec.SECP256R1):
                return False
            key.verify(signature, signed, ec.ECDSA(hashes.SHA256()))
            return True
        if alg == ALG_EDDSA:
            if not isinstance(key, ed25519.Ed25519PublicKey):
                return False
            key.verify(signature, signed)
            return True
    except (InvalidSignature, ValueError):
        return False
    return False


# ----------------------------------------------------------------------------
# origin rules
# ----------------------------------------------------------------------------
def origin_allowed_for_rp(origin: str, rp_id: str) -> bool:
    """Browser rule: the RP ID must equal the origin's host or be a
    registrable suffix of it; https is required except on localhost."""
    try:
        parts = urlsplit(origin)
    except Exception:
        return False
    host = (parts.hostname or "").lower()
    if parts.path not in ("", "/") or parts.query or parts.fragment or parts.username or parts.password:
        return False
    if not host:
        return False
    rp_id = rp_id.lower()
    if not (host == rp_id or host.endswith("." + rp_id)):
        return False
    if parts.scheme == "https":
        return True
    if parts.scheme == "http":
        return host == "localhost" or host.endswith(".localhost")
    return False


# ----------------------------------------------------------------------------
# receipt verification
# ----------------------------------------------------------------------------
RECEIPT_FIELDS = (
    "credential_id",
    "authenticator_data",
    "client_data_json",
    "signature",
    "digest",
    "approval_id",
    "nonce",
    "alg",
)


def verify_receipt(
    receipt: Dict[str, Any],
    public_key: bytes,
    expected_digest: str,
    approval_id: str,
    nonce: str,
    *,
    expected_origins: Optional[List[str]] = None,
    expected_rp_id: Optional[str] = None,
    expected_grant_digest: Optional[str] = None,
    require_user_verification: bool = False,
) -> bool:
    """Verify an ASU approval receipt offline. Pure: no I/O, no clock, no store.

    Checks: receipt binds to (expected_digest, approval_id, nonce); the
    challenge in clientDataJSON equals the recomputed ASU challenge (including
    h_grant if the receipt declares a grant); type is ``webauthn.get``; the
    origin is acceptable (in ``expected_origins`` if given, otherwise
    consistent with the RP ID); rpIdHash matches the RP ID; the UP flag is set;
    and the ES256/EdDSA signature over ``authData || SHA-256(clientDataJSON)``
    verifies under ``public_key``.

    Returns False on any failure (never raises for malformed input).
    """
    try:
        return _verify_receipt(
            receipt,
            public_key,
            expected_digest,
            approval_id,
            nonce,
            expected_origins,
            expected_rp_id,
            expected_grant_digest,
            require_user_verification,
        )
    except Exception:
        return False


def _verify_receipt(
    receipt,
    public_key,
    expected_digest,
    approval_id,
    nonce,
    expected_origins,
    expected_rp_id,
    expected_grant_digest,
    require_uv,
) -> bool:
    if not isinstance(receipt, dict):
        return False
    if receipt.get("v") is not None and receipt.get("v") != RECEIPT_VERSION:
        return False  # v1 receipts (non-injective challenge) are rejected
    for f in RECEIPT_FIELDS:
        if f not in receipt:
            return False
    expected_digest = expected_digest.lower()
    if not hmac.compare_digest(str(receipt["digest"]).lower(), expected_digest):
        return False
    if receipt["approval_id"] != approval_id or receipt["nonce"] != nonce:
        return False

    h_grant = receipt.get("grant_digest")
    if h_grant is not None and not isinstance(h_grant, str):
        return False
    if expected_grant_digest is not None:
        if h_grant is None or h_grant.lower() != expected_grant_digest.lower():
            return False
    # If the receipt carries the grant constraints, they must hash to h_grant.
    if receipt.get("grant") is not None:
        if h_grant is None or grant_digest(receipt["grant"]) != h_grant.lower():
            return False

    challenge = compute_challenge(expected_digest, approval_id, nonce, h_grant)

    auth_data = b64u_decode(receipt["authenticator_data"])
    cdj_bytes = b64u_decode(receipt["client_data_json"])
    signature = b64u_decode(receipt["signature"])
    alg = int(receipt["alg"])
    if alg not in SUPPORTED_ALGS:
        return False

    client_data = json.loads(cdj_bytes.decode("utf-8"))
    if not isinstance(client_data, dict):
        return False
    if client_data.get("type") != "webauthn.get":
        return False
    cd_challenge = client_data.get("challenge")
    if not isinstance(cd_challenge, str):
        return False
    if not hmac.compare_digest(b64u_decode(cd_challenge), challenge):
        return False
    if client_data.get("crossOrigin") is True:
        return False
    origin = client_data.get("origin")
    if not isinstance(origin, str):
        return False

    rp_id = expected_rp_id or receipt.get("rp_id") or "localhost"
    if expected_origins is not None:
        if origin not in expected_origins:
            return False
    if not origin_allowed_for_rp(origin, rp_id):
        return False

    if len(auth_data) < 37:
        return False
    if not hmac.compare_digest(auth_data[:32], hashlib.sha256(rp_id.encode("utf-8")).digest()):
        return False
    flags = auth_data[32]
    if not flags & FLAG_UP:
        return False
    if require_uv and not flags & FLAG_UV:
        return False
    # self-asserted metadata must agree with the signed flags (CR-7)
    if receipt.get("user_verified") is True and not flags & FLAG_UV:
        return False

    signed = auth_data + hashlib.sha256(cdj_bytes).digest()
    return verify_assertion_signature(public_key, alg, signed, signature)


def authenticator_flags(receipt: Dict[str, Any]) -> Dict[str, Any]:
    """Flag bits and sign count read from the SIGNED authenticatorData (never
    from the receipt's self-asserted metadata such as ``user_verified``)."""
    ad = b64u_decode(receipt["authenticator_data"])
    if len(ad) < 37:
        raise ValueError("authenticatorData too short")
    f = ad[32]
    return {"up": bool(f & FLAG_UP), "uv": bool(f & FLAG_UV), "be": bool(f & FLAG_BE),
            "bs": bool(f & FLAG_BS), "sign_count": int.from_bytes(ad[33:37], "big")}


def alg_of_public_key(public_key: bytes) -> int:
    key, alg = load_public_key(public_key)
    if alg is not None:
        return alg
    if isinstance(key, ec.EllipticCurvePublicKey):
        return ALG_ES256
    if isinstance(key, ed25519.Ed25519PublicKey):
        return ALG_EDDSA
    raise ValueError("unsupported key")
