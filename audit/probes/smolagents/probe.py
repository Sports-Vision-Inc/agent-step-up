"""Probe: smolagents human-in-the-loop (analysis of available surfaces).

smolagents ships NO built-in per-tool human-approval API. The only related surfaces
are:
  - MultiStepAgent.interrupt(): sets a flag that aborts the run at the next step
    boundary (a kill switch, not an approval).
  - step_callbacks: callables invoked AFTER each ActionStep (post-hoc observation),
    in the same process; they cannot gate a tool call before it executes.
The exported `Confirm` is `rich.prompt.Confirm` used only by the CLI config wizard.
Any real approval gate must be hand-built by the integrator inside a tool, running
in the agent's own process. We verify these facts programmatically.
Ref: smolagents/agents.py (interrupt, _setup_step_callbacks), smolagents/cli.py.
"""
import importlib.metadata as M, sys, os, inspect
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from common import write_evidence, row, emit

RT = "smolagents"
VER = M.version("smolagents")

import smolagents
from smolagents import MultiStepAgent


def main():
    rows = []
    # Verify the absence of any approval API by name.
    names = [n for n in dir(smolagents) if any(k in n.lower() for k in ("approv", "confirm", "human"))]
    agent_methods = [m for m in dir(MultiStepAgent) if any(k in m.lower() for k in ("approv", "confirm", "human"))]
    confirm_src = "rich.prompt" if "from rich.prompt import" in inspect.getsource(
        __import__("smolagents.cli", fromlist=["x"])) else "?"
    # Outcome computed from API introspection: n/a iff MultiStepAgent exposes no approval/
    # confirm/human method and the only module-level match is rich.prompt.Confirm (a CLI
    # prompt helper). If an approval API appears in a future version this yields not_run.
    absent = (not agent_methods) and set(names) <= {"Confirm"}
    NA = "na" if absent else "not_run"
    base = (f"module-level approval/confirm/human names = {names} "
            f"(Confirm is {confirm_src}); MultiStepAgent approval methods = {agent_methods}; "
            f"has interrupt() kill-switch = {hasattr(MultiStepAgent, 'interrupt')}.")

    rows.append(row(RT, VER, "T1_P1_agent_independence", NA,
        write_evidence("smolagents", "T1", base + "\nNo built-in approval surface exists to "
        "be agent-independent; any HITL gate is integrator code in the agent's own process."),
        "no built-in human-approval mechanism; interrupt() is a kill switch and step_callbacks "
        "are post-hoc in-process observers. Any approval is DIY and agent-reachable."))

    rows.append(row(RT, VER, "T2_P2_effect_binding", NA,
        write_evidence("smolagents", "T2", base + "\nNo approval artifact exists to bind to an effect."),
        "no approval mechanism, hence no effect binding; tools execute without a built-in "
        "human gate."))

    rows.append(row(RT, VER, "T3_P3_single_use", NA,
        write_evidence("smolagents", "T3", base),
        "no approval token exists to be single-use."))

    rows.append(row(RT, VER, "T4_P4_trusted_rendering", NA,
        write_evidence("smolagents", "T4", base + "\nNo framework rendering of any approval card."),
        "no approval surface, hence no trusted rendering; nothing is shown to a human by the "
        "framework before a tool runs."))

    rows.append(row(RT, VER, "T5_P5_non_repudiation", NA,
        write_evidence("smolagents", "T5", base),
        "no approval record exists, signed or otherwise."))

    rows.append(row(RT, VER, "T6_P7_flood_resistance", NA,
        write_evidence("smolagents", "T6", base),
        "no approval requests are generated by the framework, so no rate-limit primitive "
        "applies; equally none is provided for integrator-built gates."))

    emit(rows)


main()
